EOF

    # Restart SSH with testing first
    log_info "Testing SSH configuration..."
    if sshd -t 0<&1; then
        systemctl restart sshd
        log_success "SSH hardened and restarted"
    else
        log_error "SSH configuration test failed. Restoring backup..."
        # Restore from backup if available
        cp /root/backups/hardening_*/sshd_config.bak /etc/ssh/sshd_config
        exit 1
    fi
}

################################################################################
# Firewall Configuration
################################################################################

configure_firewall() {
    log_info "Configuring UFW firewall..."

    # Reset firewall to default
    ufw --force reset

    # Set default policies
    ufw default deny incoming
    ufw default allow outgoing

    # Allow SSH (CHANGE PORT IF CUSTOM)
    ufw allow 2222/tcp comment 'SSH'

    # Allow HTTP/HTTPS (if web server)
    ufw allow 80/tcp comment 'HTTP'
    ufw allow 443/tcp comment 'HTTPS'

    # Allow FastAPI backend (if needed)
    ufw allow 8000/tcp comment 'FastAPI'

    # Rate limiting for SSH
    ufw limit 2222/tcp comment 'SSH rate limit'

    # Enable logging
    ufw logging on

    # Enable firewall
    echo "y" | ufw enable

    # Show status
    ufw status verbose

    log_success "Firewall configured and enabled"
}

