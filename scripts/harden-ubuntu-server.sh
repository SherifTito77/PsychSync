################################################################################
# System Hardening
################################################################################

harden_system() {
    log_info "Applying system hardening..."

    # Disable unnecessary services
    log_info "Disabling unnecessary services..."

    # List of services to disable
    SERVICES_TO_DISABLE=(
        "avahi-daemon"
        "cups"
        "dns-clean"
        "exim4"
        "saned"
        "spamd"
        "bluetooth"
        "hidd"
        "pand"
        "dund"
    )

    for service in "${SERVICES_TO_DISABLE[@]}"; do
        if systemctl is-active --quiet "$service" 2>/dev/null; then
            systemctl stop "$service"
            systemctl disable "$service"
            log_success "Disabled $service"
        fi
    done

    # Secure /tmp
    if ! grep -q "/tmp" /etc/fstab; then
        log_warning "Consider creating separate partition for /tmp with noexec,nodev,nosuid"
    fi

    # Disable core dumps
    cat > /etc/security/limits.d/50-security.conf << 'EOF'
* hard core 0
* soft core 0
EOF

    # Restrict access to compilation tools
    if [[ -f /usr/bin/gcc ]]; then
        chmod 750 /usr/bin/gcc
        chown root:compiler-users /usr/bin/gcc 2>/dev/null || true
    fi

    # Secure cron
    touch /etc/cron.allow
    chmod 600 /etc/cron.allow
    rm -f /etc/cron.deny

    # Restrict at
    touch /etc/at.allow
    chmod 600 /etc/at.allow
    rm -f /etc/at.deny

    log_success "System hardening applied"
}

################################################################################
# Password Policy
################################################################################

configure_password_policy() {
    log_info "Configuring password policy..."

    # Configure PAM password quality
    cat > /etc/security/pwquality.conf << 'EOF'
# Password Quality Controls
minlen = 14
minclass = 3
maxrepeat = 3
dcredit = -1
ucredit = -1
lcredit = -1
ocredit = -1
difok = 3
enforce_for_root
EOF

    # Configure login defs
    backup_file "/etc/login.defs"

    sed -i 's/^PASS_MAX_DAYS.*/PASS_MAX_DAYS 90/' /etc/login.defs
    sed -i 's/^PASS_MIN_DAYS.*/PASS_MIN_DAYS 1/' /etc/login.defs
    sed -i 's/^PASS_WARN_AGE.*/PASS_WARN_AGE 7/' /etc/login.defs
    sed -i 's/^LOGIN_RETRIES.*/LOGIN_RETRIES 3/' /etc/login.defs
    sed -i 's/^LOGIN_TIMEOUT.*/LOGIN_TIMEOUT 60/' /etc/login.defs

    # Configure password aging
    cat >> /etc/pam.d/common-password << 'EOF'
# Password hashing algorithm
password [success=1 default=ignore] pam_unix.so obscure sha512 shadow yescrypt
EOF

    log_success "Password policy configured"
}

