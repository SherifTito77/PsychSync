#!/bin/bash

################################################################################
# Ubuntu Server Hardening Script for SaaS Production
# Purpose: Automate security hardening of Ubuntu servers for production use
# Based on: CIS Benchmark, NIST 800-53, PCI DSS Requirements
#
# Usage: sudo bash harden-ubuntu-server.sh
#
# WARNING: This script makes significant changes to your server configuration.
# Review and test in a non-production environment first!
################################################################################

set -euo pipefail  # Exit on error, undefined vars, pipe failures

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Logging
LOG_FILE="/var/log/server_hardening_$(date +%Y%m%d_%H%M%S).log"
exec > >(tee -a "$LOG_FILE")
exec 2>&1

################################################################################
# Helper Functions
################################################################################

log_info() {
    echo -e "${BLUE}[INFO]${NC} $1"
}

log_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

log_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

check_root() {
    if [[ $EUID -ne 0 ]]; then
        log_error "This script must be run as root (use sudo)"
        exit 1
    fi
}

backup_file() {
    local file=$1
    if [[ -f "$file" ]]; then
        local backup_dir="/root/backups/hardening_$(date +%Y%m%d)"
        mkdir -p "$backup_dir"
        cp "$file" "$backup_dir/$(basename $file).bak"
        log_success "Backed up $file to $backup_dir"
    fi
}

