        total_scenarios = sum(c.get("test_scenarios", c.get("feedback_questions", c.get("hr_scenarios", c.get("workflow_scenarios", c.get("approval_criteria", 0))))) for c in components.values())
        avg_success_score = sum(c["success_score"] for c in components.values()) / len(components)
        ready_components = len([c for c in components.values() if c["production_readiness"] == "READY"])

