        avg_business_value = sum(business_value_scores.get(c["business_value"], 50) for c in components.values()) / len(components)

        # Production readiness calculation
        critical_components = ["team_leader_uat", "hr_department_uat", "business_workflow_uat", "uat_approval"]
        critical_ready = all(components[comp]["production_readiness"] == "READY" for comp in critical_components)

        readiness_score = (avg_success_score * 0.4) + (avg_business_value * 0.3) + ((ready_components / len(components)) * 100 * 0.2) + (critical_ready * 100 * 0.1)

